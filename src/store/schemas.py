def conform(df: pd.DataFrame) -> pd.DataFrame:
    """Lower-case names, int64 ts, UTC event_time, float numerics, str text.

    Rules: `ts` and any `*_ts` column -> int64; other numbers -> float64;
    booleans -> int64; everything else -> string ('' for missing).
    """
    df = df.copy()
    df.columns = [c.lower() for c in df.columns]
    if "ts" in df:
        df["ts"] = pd.to_numeric(df["ts"]).astype("int64")
        df["event_time"] = pd.to_datetime(df["ts"], unit="s", utc=True)
    for c in df.columns:
        if c in ("ts", "event_time"):
            continue
        if pd.api.types.is_bool_dtype(df[c]):
            df[c] = df[c].astype("int64")
        elif c.endswith("_ts"):
            df[c] = pd.to_numeric(df[c], errors="coerce").fillna(0).astype("int64")
        elif pd.api.types.is_numeric_dtype(df[c]):
            df[c] = df[c].astype("float64")
        elif pd.api.types.is_datetime64_any_dtype(df[c]):
            df[c] = pd.to_datetime(df[c], utc=True)
        else:
            df[c] = df[c].astype("string").fillna("").astype(str)
    return df
